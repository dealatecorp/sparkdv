import {chromium, expect} from '@playwright/test';
import fs from 'node:fs/promises';
const browser = await chromium.launch({channel:'chromium'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror', e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/products');
const showcase=page.locator('.spark-showcase');
async function selectProduct(name) {
  for (let i=0;i<17;i++) {
    if (await showcase.locator('.snp-title').textContent() === name) return;
    await showcase.getByRole('button',{name:'Next product',exact:true}).click();
  }
  throw Error('Product not found: '+name);
}
await showcase.scrollIntoViewIfNeeded();
await expect(showcase.locator('.snp-title')).toHaveText('Nanion Lite');
await page.waitForTimeout(1000);
const geometry = await showcase.locator('.snp-stage').evaluate(stage => {
  const s=stage.getBoundingClientRect();
  const image=stage.querySelector('.snp-tilt img:not([aria-hidden])').getBoundingClientRect();
  return image.top >= s.top && image.bottom <= s.bottom;
});
expect(geometry).toBe(true);
await page.screenshot({path:'audit/screenshots/brand-products-desktop.png'});
await selectProduct('Nanion Lite Pro');
await expect(showcase.locator('.snp-title')).toHaveText('Nanion Lite Pro');
await showcase.getByRole('button',{name:'Quantity 2',exact:true}).click();
await expect(showcase.locator('.snp-price')).toHaveText('₹1398');
await showcase.getByRole('button',{name:'Add to cart',exact:true}).click();
await expect(page.locator('.cart-drawer')).toBeVisible();
await expect(page.locator('.cart-drawer')).toContainText('Nanion Lite Pro');
await expect(page.locator('.cart-drawer .quantity>span')).toHaveText('2');
await page.keyboard.press('Escape');
await showcase.locator('.snp-thumb').first().click();
await expect(page.getByRole('dialog',{name:'Nanion Lite Pro photos'})).toBeVisible();
await page.getByRole('button',{name:'Next photo',exact:true}).click();
await expect(page.locator('.snp-vbar strong')).toContainText('close-up');
await page.keyboard.press('Escape');
await expect(page.locator('.snp-viewer')).toHaveCount(0);
await expect(showcase.locator('.snp-thumb').first()).toBeFocused();
await showcase.getByRole('button',{name:'Save to favourites'}).click();
await expect(showcase.getByRole('button',{name:'Save to favourites'})).toHaveAttribute('aria-pressed','true');
await page.getByRole('textbox',{name:'Search products'}).fill('no-such-product');
await expect(page.getByText('No products found')).toBeVisible();
await page.getByRole('button',{name:'Clear filters',exact:true}).last().click();
await expect(showcase).toBeVisible();
const {products}=await import('../src/data.js');
const coming=products.find(p=>p.coming);
await selectProduct(coming.name);
await expect(showcase.getByRole('link',{name:'ENQUIRE',exact:true})).toBeVisible();
await expect(showcase.locator('.snp-stock')).toHaveText('Coming soon');
await selectProduct('Nanion Lite');
await expect(showcase.locator('.snp-price')).toHaveText('₹599');
await page.setViewportSize({width:390,height:844});
await showcase.scrollIntoViewIfNeeded();
await page.screenshot({path:'audit/screenshots/brand-products-mobile.png',fullPage:true});
await showcase.locator('.snp-buy').scrollIntoViewIfNeeded();
await page.screenshot({path:'audit/screenshots/brand-product-controls-mobile.png'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
await page.goto('http://127.0.0.1:5173/');
await page.waitForTimeout(3800);
await page.screenshot({path:'audit/screenshots/brand-home-mobile.png'});
await page.emulateMedia({reducedMotion:'reduce'});
await page.locator('#portfolio').scrollIntoViewIfNeeded();
await page.locator('#portfolio').getByRole('button',{name:'Restorations',exact:true}).click();
await expect(showcase.locator('.snp-title')).not.toBeEmpty();
await page.screenshot({path:'audit/screenshots/brand-home-showcase-mobile.png'});
await page.setViewportSize({width:1440,height:1000});
await page.goto('http://127.0.0.1:5173/');
await page.waitForTimeout(1500);
await page.screenshot({path:'audit/screenshots/brand-home-desktop.png'});
await page.locator('#portfolio').scrollIntoViewIfNeeded();
await page.screenshot({path:'audit/screenshots/brand-home-showcase-desktop.png'});
await fs.writeFile('audit/brand-showcase-qa.json',JSON.stringify({errors,checks:['Product switch','Quantity pricing','Real cart quantity','Gallery and keyboard close','Focus restoration','Favourite toggle','Search empty state and recovery','Mobile overflow','Homepage category filters','Reduced motion']},null,2));
await browser.close();
if(errors.length)throw Error(errors.join('\n'));
console.log('Brand showcase checks passed');
