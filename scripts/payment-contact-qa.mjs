import {chromium,expect} from '@playwright/test';
import {products} from '../src/data.js';
const b=await chromium.launch({channel:'chromium'});
const p=await b.newPage({viewport:{width:1440,height:1000}});
const errors=[];p.on('pageerror',e=>errors.push(e.message));
await p.addInitScript(item=>localStorage.setItem('spark-cart',JSON.stringify([{...item,qty:2}])),products[0]);
await p.goto('http://127.0.0.1:5173/products');
await p.getByRole('link',{name:'Contact',exact:true}).click();
await expect(p).toHaveURL(/\/products$/);
const dialog=p.getByRole('dialog',{name:'Let’s talk.'});
await expect(dialog).toBeVisible();
await dialog.getByRole('button',{name:'Prepare email'}).click();
await expect(dialog.locator('input:invalid').first()).toBeFocused();
await p.screenshot({path:'audit/screenshots/contact-popup-desktop.png'});
await p.keyboard.press('Escape');
await expect(dialog).toHaveCount(0);
await expect(p.getByRole('link',{name:'Contact',exact:true})).toBeFocused();
await p.getByRole('button',{name:'Open cart, 2 items'}).click();
await p.getByRole('button',{name:'Continue to demo payment'}).click();
await expect(p).toHaveURL(/\/checkout$/);
await expect(p.locator('.payment-total')).toContainText('1,198');
await p.screenshot({path:'audit/screenshots/demo-checkout-desktop.png'});
await p.getByLabel('Rejected payment',{exact:true}).check();
await p.getByRole('button',{name:/Simulate payment/}).click();
await expect(p.getByRole('button',{name:/Processing demo payment/})).toBeDisabled();
await expect(p.getByRole('heading',{name:'Demo payment declined'})).toBeVisible();
await expect(p.locator('.payment-result-icon path')).toHaveCSS('stroke-dashoffset','0px');
await p.screenshot({path:'audit/screenshots/demo-payment-declined.png'});
await p.getByRole('button',{name:'Try again'}).click();
await p.getByLabel('Demo UPI',{exact:true}).check();
await p.getByRole('button',{name:/Simulate payment/}).click();
await expect(p.getByRole('heading',{name:'Demo payment complete'})).toBeVisible();
await expect(p.locator('.payment-result-icon path')).toHaveCSS('stroke-dashoffset','0px');
await p.screenshot({path:'audit/screenshots/demo-payment-success.png'});
await expect(p.getByRole('button',{name:'Open cart, 2 items'})).toBeVisible();
await p.setViewportSize({width:390,height:844});
await p.getByRole('button',{name:'Try another demo'}).click();
await p.screenshot({path:'audit/screenshots/demo-checkout-mobile.png',fullPage:true});
expect(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
await p.goto('http://127.0.0.1:5173/contact?type=Sample%20request&product=Nanion%20Lite');
await expect(dialog).toBeVisible();
await expect(dialog.getByLabel('Enquiry type')).toHaveValue('Sample request');
await expect(dialog.getByRole('combobox',{name:'Product',exact:true})).toHaveValue('Nanion Lite');
await p.screenshot({path:'audit/screenshots/contact-popup-mobile.png'});
await p.getByRole('button',{name:'Close contact form'}).click();
await expect(dialog).toHaveCount(0);
await p.evaluate(()=>localStorage.removeItem('spark-cart'));
await p.goto('http://127.0.0.1:5173/checkout');
// Init script seeds the cart on full navigation; explicitly check empty state in a fresh context.
const empty=await b.newPage();await empty.goto('http://127.0.0.1:5173/checkout');
await expect(empty.getByRole('heading',{name:'Your cart is empty.'})).toBeVisible();
await b.close();
if(errors.length)throw Error(errors.join('\n'));
console.log('Payment approval, rejection, retry, cart preservation, empty checkout, contact popup, deep link, focus, Escape and mobile checks passed.');
