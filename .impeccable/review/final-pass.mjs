import { chromium } from '@playwright/test';

const browser = await chromium.launch({ channel: 'chromium' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
await page.locator('[data-testid="landing-reveal"]').waitFor({ state: 'detached', timeout: 9000 });
await page.waitForTimeout(900);
await page.screenshot({ path: '.impeccable/review/hero-desktop.png' });
for (let y = 0; y < await page.evaluate(() => document.body.scrollHeight); y += 700) { await page.evaluate(y => scrollTo(0, y), y); await page.waitForTimeout(100); }
await page.waitForTimeout(700);
await page.evaluate(() => scrollTo(0, document.body.scrollHeight));
await page.waitForTimeout(500);
await page.screenshot({ path: '.impeccable/review/footer-desktop.png' });
await page.evaluate(() => scrollTo(0, 0));
await page.waitForTimeout(250);
await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true });
const brand = await page.locator('.shop-hero-brand').innerText();
const firstProduct = await page.locator('.snp-title').innerText();
const initialSrc = await page.locator('.snp-shoe:not(.snp-reflect):not(.snp-sheen)').filter({ visible: true }).getAttribute('src');
const desktop = await page.evaluate(() => ({ root: document.querySelector('.brand-product-hero')?.getBoundingClientRect().toJSON(), body: document.querySelector('.brand-product-hero .snp-body')?.getBoundingClientRect().toJSON(), stage: document.querySelector('.brand-product-hero .snp-stage')?.getBoundingClientRect().toJSON(), title: document.querySelector('.brand-product-hero .snp-title')?.getBoundingClientRect().toJSON(), image: document.querySelector('.brand-product-hero .snp-shoe:not(.snp-reflect):not(.snp-sheen)[style*="visible"]')?.getBoundingClientRect().toJSON() }));
await page.getByRole('button', { name: 'Next product' }).click();
await page.waitForTimeout(500);
const nextProduct = await page.locator('.snp-title').innerText();
const nextSrc = await page.locator('.snp-shoe:not(.snp-reflect):not(.snp-sheen)').filter({ visible: true }).getAttribute('src');
await page.getByRole('button', { name: 'Quantity 2' }).click();
await page.getByRole('button', { name: 'Add to cart' }).click();
await page.locator('.cart-drawer').waitFor({ state: 'visible' });
const cartDrawer = await page.locator('.cart-drawer').innerText();
await page.setViewportSize({ width: 390, height: 844 });
await page.evaluate(() => localStorage.clear());
await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
await page.locator('[data-testid="landing-reveal"]').waitFor({ state: 'detached', timeout: 9000 });
await page.waitForTimeout(500);
await page.evaluate(() => { history.scrollRestoration = 'manual'; document.activeElement?.blur(); document.scrollingElement.scrollTop = 0; });
await page.waitForTimeout(1000);
console.log('mobileScreenshotScrollY', await page.evaluate(() => scrollY));
await page.screenshot({ path: '.impeccable/review/hero-mobile.png' });
for (let y = 0; y < await page.evaluate(() => document.body.scrollHeight); y += 550) { await page.evaluate(y => scrollTo(0, y), y); await page.waitForTimeout(100); }
await page.waitForTimeout(700);
await page.evaluate(() => scrollTo(0, document.body.scrollHeight));
await page.waitForTimeout(500);
await page.screenshot({ path: '.impeccable/review/footer-mobile.png' });
await page.evaluate(() => scrollTo(0, 0));
await page.waitForTimeout(250);
await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true });
const mobile = await page.evaluate(() => ({ viewport: innerWidth, page: document.documentElement.scrollWidth, hero: document.querySelector('.brand-product-hero')?.getBoundingClientRect().toJSON(), title: document.querySelector('.snp-title')?.getBoundingClientRect().toJSON(), productImage: document.querySelector('.snp-shoe')?.getBoundingClientRect().toJSON(), buy: document.querySelector('.snp-buy')?.getBoundingClientRect().toJSON(), actions: document.querySelector('.snp-actions')?.getBoundingClientRect().toJSON() }));
await page.goto('http://127.0.0.1:5173/science', { waitUntil: 'networkidle' });
const scienceHeading = await page.locator('h1').first().innerText();
console.log(JSON.stringify({ brand, firstProduct, initialSrc, nextProduct, nextSrc, cartDrawer, desktop, mobile, scienceHeading, errors }, null, 2));
await browser.close();
